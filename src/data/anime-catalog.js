export function generateEpisodesForAnime(anime, seasonNumber = 1) {
  const totalEps = anime.episodes_count || 12;
  const totalSeasons = anime.seasons_count || 1;
  const epsThisSeason = Math.min(24, Math.ceil(totalEps / totalSeasons));

  return Array.from({ length: epsThisSeason }, (_, i) => {
    const epNum = i + 1;
    return {
      episode_number: epNum,
      season_number: seasonNumber,
      name: `${anime.title} - ${seasonNumber}. Sezon ${epNum}. Bölüm`,
      overview: `${anime.title} anime serisinin ${seasonNumber}. sezon ${epNum}. bölümü. Türkçe altyazılı 1080p Full HD kalitede kesintisiz izleyebilirsiniz.`,
      air_date: anime.first_air_date || "2024",
      runtime: 24,
      still_path: anime.backdrop_path || anime.poster_path,
      vote_average: anime.vote_average ? anime.vote_average.toString() : "8.8"
    };
  });
}


